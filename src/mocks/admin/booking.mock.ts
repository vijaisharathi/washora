export function updateMockBookingStatusInStore(
  organizationId: string,
  bookingId: string,
  newStatus: BookingStatus,
  actorName: string = "Admin Operations",
  reason?: string
): BookingOrder {
  const store = organizationId === "ORG-0002" ? org0002BookingsStore : org0001BookingsStore;
  const index = store.findIndex((b) => b.id === bookingId);
  if (index === -1) {
    throw new Error(`Booking ${bookingId} not found in organization ${organizationId}`);
  }

  const currentStatus = store[index].status;
  const allowed = ALLOWED_STATUS_TRANSITIONS[currentStatus];
  if (!allowed.includes(newStatus)) {
    throw new Error(
      `Invalid status transition: Cannot transition from ${currentStatus} to ${newStatus}`
    );
  }

  const now = new Date().toISOString();
  store[index] = {
    ...store[index],
    status: newStatus,
    updatedAt: now,
    lastUpdatedBy: actorName,
  };

  // Add activity
  let actType: BookingActivity["type"] = "booking_updated";
  if (newStatus === "confirmed") actType = "booking_confirmed";
  else if (newStatus === "in_progress") actType = "booking_started";
  else if (newStatus === "completed") actType = "booking_completed";
  else if (newStatus === "cancelled") actType = "booking_cancelled";

  const description =
    reason ||
    `Status transitioned from ${currentStatus} to ${newStatus} by ${actorName}`;

  addMockBookingActivity({
    id: `ACT-${bookingId}-${Date.now()}`,
    bookingId,
    type: actType,
    description,
    timestamp: now,
    actorName,
    status: newStatus,
  });

  return store[index];
}

export function addMockBookingActivity(activity: BookingActivity): void {
  if (!bookingActivitiesStore[activity.bookingId]) {
    bookingActivitiesStore[activity.bookingId] = [];
  }
  bookingActivitiesStore[activity.bookingId].unshift(activity);
}

