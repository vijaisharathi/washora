export function updateMockServiceInStore(
  organizationId: string,
  updatedService: Service
): Service {
  const store =
    organizationId === "ORG-0002" ? org0002ServicesStore : org0001ServicesStore;
  const index = store.findIndex((s) => s.id === updatedService.id);
  if (index !== -1) {
    const merged = hydrateService({
      ...store[index],
      ...updatedService,
      updatedAt: new Date().toISOString(),
    });
    store[index] = merged;
    return store[index];
  }
  return hydrateService(updatedService);
}

export function updateMockServiceStatusInStore(
  organizationId: string,
  serviceId: string,
  newStatus: ServiceStatus,
  performedBy: string = "Admin Operations",
  reason?: string
): Service {
  const store =
    organizationId === "ORG-0002" ? org0002ServicesStore : org0001ServicesStore;
  const index = store.findIndex((s) => s.id === serviceId);
  if (index === -1) {
    throw new Error(`Service ${serviceId} not found in organization ${organizationId}`);
  }

  const currentStatus = store[index].status;
  const allowed = ALLOWED_SERVICE_STATUS_TRANSITIONS[currentStatus];
  if (!allowed.includes(newStatus)) {
    throw new Error(
      `Invalid status transition: Cannot transition from ${currentStatus} to ${newStatus}`
    );
  }

  const now = new Date().toISOString();
  store[index] = hydrateService({
    ...store[index],
    status: newStatus,
    updatedAt: now,
  });

  let actType: ServiceActivity["type"] = "service_updated";
  if (newStatus === "Active") actType = "service_activated";
  else if (newStatus === "Inactive") actType = "service_deactivated";
  else if (newStatus === "Archived") actType = "service_archived";

  const description =
    reason || `Status transitioned from ${currentStatus} to ${newStatus} by ${performedBy}`;

  addMockServiceActivity({
    id: `ACT-${serviceId}-${Date.now()}`,
    serviceId,
    type: actType,
    description,
    timestamp: now,
    performedBy,
  });

  return store[index];
}

export function addMockServiceActivity(activity: ServiceActivity): void {
  if (!serviceActivitiesStore[activity.serviceId]) {
    serviceActivitiesStore[activity.serviceId] = [];
  }
  serviceActivitiesStore[activity.serviceId].unshift(activity);
}

