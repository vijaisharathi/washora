// Helper to compute displayPrice and activeBookings
function hydrateService(s: any): Service {
  return {
    ...s,
    displayPrice: s.displayPrice ?? (s.basePrice + s.serviceFee),
    activeBookings:
      s.activeBookings ??
      Math.max(0, s.totalBookings - s.completedBookings - s.cancelledBookings),
  };
}

