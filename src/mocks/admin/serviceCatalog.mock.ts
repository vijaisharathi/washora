// Deterministic activities map
let serviceActivitiesStore: Record<string, ServiceActivity[]> = {};

function initializeActivities() {
  serviceActivitiesStore = {};
  const allServices = [...INITIAL_ORG_0001_SERVICES, ...INITIAL_ORG_0002_SERVICES];

  allServices.forEach((s) => {
    const list: ServiceActivity[] = [
      {
        id: `ACT-${s.id}-01`,
        serviceId: s.id,
        type: "service_created",
        description: `Service "${s.name}" registered in catalog under ${s.category}`,
        timestamp: s.createdAt,
        performedBy: "Operations Administrator",
      },
    ];

    if (s.status === "Active") {
      list.push({
        id: `ACT-${s.id}-02`,
        serviceId: s.id,
        type: "service_activated",
        description: `Service activated and made available for customer bookings at ₹${s.basePrice + s.serviceFee}`,
        timestamp: s.updatedAt,
        performedBy: "Catalog Lead",
      });
    } else if (s.status === "Inactive") {
      list.push({
        id: `ACT-${s.id}-02`,
        serviceId: s.id,
        type: "service_deactivated",
        description: "Service temporarily paused from active catalog discovery",
        timestamp: s.updatedAt,
        performedBy: "Operations Manager",
      });
    } else if (s.status === "Archived") {
      list.push({
        id: `ACT-${s.id}-02`,
        serviceId: s.id,
        type: "service_archived",
        description: "Service permanently retired from platform catalog offerings",
        timestamp: s.updatedAt,
        performedBy: "System Administrator",
      });
    }

    serviceActivitiesStore[s.id] = list;
  });
}

